// Writes the database side of the company walls (Phase 1, step 3): one trigger per company
// table. Run after adding a table or a link between tables, and put the output in a migration:
//   npx tsx src/scripts/companyWallsSql.ts > prisma/migrations/<new>/migration.sql
// The test "every company table has its walls" fails until the new table has its trigger.
//
// Each trigger, on every new or changed row:
//  1. a row saved without a company (outside a signed-in request, or by older code during a
//     deploy) takes the company of the record it belongs to (its person, task, project...);
//     with nothing to take it from, it is 99 Technologies' (company 1);
//  2. refuses a row that points at a record of another company;
//  3. refuses moving a row to another company.
import { Prisma } from '@prisma/client'
import { NOT_WALLED } from '../lib/tenancy'


export type WalledTable = { table: string; parents: { column: string; table: string }[] }

export function walledTables(): WalledTable[] {
  const models = Prisma.dmmf.datamodel.models
  const walled = new Set(models.filter((m) => m.fields.some((f) => f.name === 'companyId' && f.kind === 'scalar') && !NOT_WALLED.has(m.name)).map((m) => m.name))
  return models.filter((m) => walled.has(m.name)).map((m) => ({
    table: m.name,
    parents: m.fields
      .filter((f) => f.kind === 'object' && walled.has(f.type) && (f.relationFromFields?.length ?? 0) === 1 && f.relationToFields?.[0] === 'id')
      .map((f) => ({ column: f.relationFromFields![0], table: f.type })),
  }))
}

const q = (s: string) => `"${s.replace(/"/g, '""')}"`
export const triggerName = (table: string) => `${table}_company_wall`
const fnName = (table: string) => `mq_wall_${table}`

export function tableWallSql(t: WalledTable): string {
  const derive = t.parents.map((p) => `    IF c IS NULL AND NEW.${q(p.column)} IS NOT NULL THEN SELECT "companyId" INTO c FROM ${q(p.table)} WHERE "id" = NEW.${q(p.column)}; END IF;`).join('\n')
  const check = t.parents.map((p) => [
    `  IF NEW.${q(p.column)} IS NOT NULL AND (TG_OP = 'INSERT' OR NEW.${q(p.column)} IS DISTINCT FROM OLD.${q(p.column)}) THEN`,
    `    SELECT "companyId" INTO c FROM ${q(p.table)} WHERE "id" = NEW.${q(p.column)};`,
    `    IF c IS NOT NULL AND c <> NEW."companyId" THEN RAISE EXCEPTION 'metriq company wall: ${t.table}.${p.column} points at another company' USING ERRCODE = 'P0420'; END IF;`,
    `  END IF;`,
  ].join('\n')).join('\n')
  return `CREATE OR REPLACE FUNCTION ${q(fnName(t.table))}() RETURNS trigger AS $$
DECLARE c TEXT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW."companyId" IS DISTINCT FROM OLD."companyId" THEN
    RAISE EXCEPTION 'metriq company wall: a ${t.table} row cannot move to another company' USING ERRCODE = 'P0420';
  END IF;
  IF NEW."companyId" IS NULL OR NEW."companyId" = '' THEN
${derive || '    NULL;'}
    NEW."companyId" := COALESCE(c, 'company-1');
    c := NULL;
  END IF;
${check}
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS ${q(triggerName(t.table))} ON ${q(t.table)};
CREATE TRIGGER ${q(triggerName(t.table))} BEFORE INSERT OR UPDATE ON ${q(t.table)} FOR EACH ROW EXECUTE FUNCTION ${q(fnName(t.table))}();
`
}

export function companyWallSql(): string {
  return walledTables().map(tableWallSql).join('\n')
}

if (require.main === module) process.stdout.write(`-- Company walls in the database (generated by src/scripts/companyWallsSql.ts).\n\n${companyWallSql()}`)
