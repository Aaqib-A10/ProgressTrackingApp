CREATE OR REPLACE FUNCTION "mq_wall_WebhookDelivery"() RETURNS trigger AS $$
DECLARE c TEXT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW."companyId" IS DISTINCT FROM OLD."companyId" THEN
    RAISE EXCEPTION 'metriq company wall: a WebhookDelivery row cannot move to another company' USING ERRCODE = 'P0420';
  END IF;
  IF NEW."companyId" IS NULL OR NEW."companyId" = '' THEN
    IF c IS NULL AND NEW."webhookId" IS NOT NULL THEN SELECT "companyId" INTO c FROM "Webhook" WHERE "id" = NEW."webhookId"; END IF;
    NEW."companyId" := COALESCE(c, 'company-1');
    c := NULL;
  END IF;
  IF NEW."webhookId" IS NOT NULL AND (TG_OP = 'INSERT' OR NEW."webhookId" IS DISTINCT FROM OLD."webhookId") THEN
    SELECT "companyId" INTO c FROM "Webhook" WHERE "id" = NEW."webhookId";
    IF c IS NOT NULL AND c <> NEW."companyId" THEN RAISE EXCEPTION 'metriq company wall: WebhookDelivery.webhookId points at another company' USING ERRCODE = 'P0420'; END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
