-- Company walls: each new table keeps its rows inside one company (generated by src/scripts/companyWallsSql.ts).
CREATE OR REPLACE FUNCTION "mq_wall_ApiKey"() RETURNS trigger AS $$
DECLARE c TEXT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW."companyId" IS DISTINCT FROM OLD."companyId" THEN
    RAISE EXCEPTION 'metriq company wall: a ApiKey row cannot move to another company' USING ERRCODE = 'P0420';
  END IF;
  IF NEW."companyId" IS NULL OR NEW."companyId" = '' THEN
    NULL;
    NEW."companyId" := COALESCE(c, 'company-1');
    c := NULL;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS "ApiKey_company_wall" ON "ApiKey";
CREATE TRIGGER "ApiKey_company_wall" BEFORE INSERT OR UPDATE ON "ApiKey" FOR EACH ROW EXECUTE FUNCTION "mq_wall_ApiKey"();

